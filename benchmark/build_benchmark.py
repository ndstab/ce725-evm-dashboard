"""Build the manual benchmark workbook.

WHAT THIS IS, AND WHAT IT IS NOT

This script lays out a plain Excel workbook in which every earned value
figure for reporting periods 5 and 6 is computed by a TYPED EXCEL FORMULA
operating on the raw inputs. It writes formulas, never results. Open the
workbook and click any cell and you will see the arithmetic, not a number
that something else produced.

The workbook is the independent benchmark required by the brief. Its
independence is in the CALCULATION, not in the data: it reads the same
budgets, percentages and costs as the Python tool, because a benchmark
against different data would compare nothing. What it establishes is that
two separately written implementations of the EVM definitions -- one in
Python, one in Excel formulas -- agree. An error in the Python engine will
not be mirrored by an Excel SUM.

What it therefore CANNOT establish, and the validation report says so
plainly, is that the underlying progress measurements are correct. If a
site engineer reports a column as 60% complete when it is 40% complete,
both implementations will agree, confidently, on a wrong EV. That error is
only catchable at site.

Why this is generated by a script rather than typed cell by cell: 19 work
packages across 12 baseline periods is 228 planned value cells, and
hand-typing them introduces exactly the transcription errors the benchmark
exists to detect. The script places the formulas; Excel evaluates them.
The formulas are the manual method.

Run:  python benchmark/build_benchmark.py
"""

from __future__ import annotations

import sys
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from evm.dataset import load_project  # noqa: E402

OUT = ROOT / "benchmark" / "EVM_Manual_Benchmark.xlsx"

# Periods the benchmark covers, as required by the brief.
BENCHMARK_PERIODS = (5, 6)

RUPEES = "#,##0.00"
INDEX_FMT = "0.000000"
PCT = "0.00%"

HEADER_FILL = PatternFill("solid", fgColor="1F3864")
HEADER_FONT = Font(bold=True, color="FFFFFF", size=10)
INPUT_FILL = PatternFill("solid", fgColor="FFF2CC")   # typed raw data
FORMULA_FILL = PatternFill("solid", fgColor="E2EFDA")  # computed by Excel
TOTAL_FILL = PatternFill("solid", fgColor="D9D9D9")
TITLE_FONT = Font(bold=True, size=13, color="1F3864")
NOTE_FONT = Font(italic=True, size=9, color="595959")

THIN = Side(style="thin", color="BFBFBF")
BOX = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def _header_row(ws, row: int, labels: list[str], widths: list[int] | None = None):
    for col, label in enumerate(labels, start=1):
        cell = ws.cell(row=row, column=col, value=label)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BOX
    if widths:
        for col, width in enumerate(widths, start=1):
            ws.column_dimensions[get_column_letter(col)].width = width
    ws.row_dimensions[row].height = 30


def _title(ws, text: str, subtitle: str = ""):
    ws["A1"] = text
    ws["A1"].font = TITLE_FONT
    if subtitle:
        ws["A2"] = subtitle
        ws["A2"].font = NOTE_FONT


def build() -> Path:
    project = load_project(ROOT / "data")
    leaves = project.leaves.reset_index(drop=True)
    n_leaf = len(leaves)
    n_periods = project.n_periods
    data_date = project.data_date

    # Pivot the raw inputs. These become typed values in the workbook; they
    # are the only numbers in it that are not computed by Excel.
    ac = project.actuals.pivot_table(
        index="wbs_id", columns="period", values="ac_period_inr", aggfunc="sum"
    ).fillna(0.0)
    pct = project.actuals.pivot_table(
        index="wbs_id", columns="period", values="pct_complete_cum", aggfunc="sum"
    ).fillna(0.0)
    pv = project.baseline.pivot_table(
        index="wbs_id", columns="period", values="pv_period_inr", aggfunc="sum"
    ).fillna(0.0)

    wb = Workbook()

    # ======================================================================
    # Read Me
    # ======================================================================
    ws = wb.active
    ws.title = "Read Me"
    ws.column_dimensions["A"].width = 110
    _title(ws, "Manual Benchmark Workbook — Earned Value Management")
    lines = [
        "",
        f"Project      {project.meta.project_name}",
        f"Code         {project.meta.project_code}",
        f"BAC          Rs {project.bac:,.2f}",
        f"Baseline     {n_periods} monthly periods",
        f"Data date    end of Period {data_date} ({project.meta.label(data_date)})",
        f"Benchmark    reporting periods {' and '.join(str(p) for p in BENCHMARK_PERIODS)}",
        "",
        "PURPOSE",
        "",
        "This workbook is the independent manual benchmark for the EVM dashboard.",
        "Every earned value figure in it is produced by a typed Excel formula acting",
        "on the raw inputs on the 'Inputs' and 'Baseline' sheets. Click any green cell",
        "to see the arithmetic. No value here is copied from the Python tool.",
        "",
        "WHAT IT PROVES",
        "",
        "That two separately written implementations of the EVM definitions agree:",
        "one in Python (the evm package), one in Excel formulas (this workbook).",
        "An arithmetic or logic error in one will not be reproduced by the other.",
        "",
        "WHAT IT DOES NOT PROVE",
        "",
        "That the inputs are right. Both implementations read the same budgets,",
        "percent-complete figures and costs. If a work package is reported at 60%",
        "complete when it is actually 40% complete, both will agree on an earned",
        "value that is wrong by Rs lakhs. No spreadsheet can detect that; only a",
        "measurement at site can. This is the single most important limitation of",
        "the whole tool and it is stated again in the user manual.",
        "",
        "COLOUR KEY",
        "",
        "    Yellow   typed raw input, the only hand-entered numbers in the workbook",
        "    Green    computed by an Excel formula",
        "    Grey     totals",
        "",
        "SHEETS",
        "",
        "    Inputs      budgets, actual cost per period, percent complete per period",
        "    Baseline    the time-phased budget and the cumulative planned value curve",
        "    Calc P5     per-package earned value calculation at end of Period 5",
        "    Calc P6     per-package earned value calculation at end of Period 6",
        "    Indices     all EVM indices and forecasts for both periods, side by side",
        "",
        "Generated by benchmark/build_benchmark.py. The script places formulas;",
        "Excel evaluates them.",
    ]
    for i, line in enumerate(lines, start=3):
        ws.cell(row=i, column=1, value=line)

    # ======================================================================
    # Inputs  (typed raw data)
    # ======================================================================
    ws = wb.create_sheet("Inputs")
    _title(
        ws, "Raw Inputs",
        "Hand-entered data. Every other number in this workbook is derived from these cells.",
    )
    first = 5
    headers = ["WBS ID", "Work Package", "Budget (Rs)"]
    headers += [f"AC P{p}" for p in range(1, data_date + 1)]
    headers += [f"%C P{p}" for p in range(1, data_date + 1)]
    _header_row(ws, 4, headers, [10, 44, 15] + [13] * data_date * 2)

    for i, row in leaves.iterrows():
        r = first + i
        wbs_id = row["wbs_id"]
        ws.cell(row=r, column=1, value=wbs_id).border = BOX
        ws.cell(row=r, column=2, value=row["name"]).border = BOX
        c = ws.cell(row=r, column=3, value=float(row["budget_inr"]))
        c.number_format, c.fill, c.border = RUPEES, INPUT_FILL, BOX
        for p in range(1, data_date + 1):
            c = ws.cell(row=r, column=3 + p, value=float(ac.loc[wbs_id, p]))
            c.number_format, c.fill, c.border = RUPEES, INPUT_FILL, BOX
            c = ws.cell(row=r, column=3 + data_date + p,
                        value=float(pct.loc[wbs_id, p]))
            c.number_format, c.fill, c.border = PCT, INPUT_FILL, BOX

    last = first + n_leaf - 1
    total_row = last + 1
    ws.cell(row=total_row, column=2, value="TOTAL").font = Font(bold=True)
    for col in [3] + [3 + p for p in range(1, data_date + 1)]:
        letter = get_column_letter(col)
        c = ws.cell(row=total_row, column=col,
                    value=f"=SUM({letter}{first}:{letter}{last})")
        c.number_format, c.fill, c.font, c.border = RUPEES, TOTAL_FILL, Font(bold=True), BOX

    ws.cell(row=total_row + 2, column=2,
            value="BAC (sum of work package budgets)").font = Font(bold=True)
    c = ws.cell(row=total_row + 2, column=3, value=f"=C{total_row}")
    c.number_format, c.font, c.fill, c.border = RUPEES, Font(bold=True), FORMULA_FILL, BOX
    ws.freeze_panes = "C5"

    inputs_rows = (first, last, total_row)

    # ======================================================================
    # Baseline  (time-phased budget + cumulative PV curve)
    # ======================================================================
    ws = wb.create_sheet("Baseline")
    _title(
        ws, "Time-Phased Budget (Planned Value)",
        "Planned value per work package per baseline period. Row 'Cumulative PV' is the S-curve.",
    )
    headers = ["WBS ID", "Work Package"] + [f"PV P{p}" for p in range(1, n_periods + 1)]
    headers += ["Row total", "Budget check"]
    _header_row(ws, 4, headers, [10, 44] + [13] * n_periods + [15, 15])

    for i, row in leaves.iterrows():
        r = first + i
        wbs_id = row["wbs_id"]
        ws.cell(row=r, column=1, value=wbs_id).border = BOX
        ws.cell(row=r, column=2, value=row["name"]).border = BOX
        for p in range(1, n_periods + 1):
            c = ws.cell(row=r, column=2 + p, value=float(pv.loc[wbs_id, p]))
            c.number_format, c.fill, c.border = RUPEES, INPUT_FILL, BOX
        last_pv_col = get_column_letter(2 + n_periods)
        c = ws.cell(row=r, column=3 + n_periods,
                    value=f"=SUM(C{r}:{last_pv_col}{r})")
        c.number_format, c.fill, c.border = RUPEES, FORMULA_FILL, BOX
        # Reconciliation: time-phased planned value must equal the budget.
        c = ws.cell(row=r, column=4 + n_periods,
                    value=f'=IF(ROUND({get_column_letter(3 + n_periods)}{r}'
                          f"-Inputs!C{r},2)=0,\"OK\",\"MISMATCH\")")
        c.fill, c.border = FORMULA_FILL, BOX
        c.alignment = Alignment(horizontal="center")

    pv_total_row = last + 1
    ws.cell(row=pv_total_row, column=2, value="TOTAL").font = Font(bold=True)
    for p in range(1, n_periods + 2):
        letter = get_column_letter(2 + p)
        c = ws.cell(row=pv_total_row, column=2 + p,
                    value=f"=SUM({letter}{first}:{letter}{last})")
        c.number_format, c.fill, c.font, c.border = RUPEES, TOTAL_FILL, Font(bold=True), BOX

    # Cumulative planned value curve. Earned Schedule interpolates along it.
    curve_row = pv_total_row + 2
    ws.cell(row=curve_row, column=2, value="Cumulative PV (S-curve)").font = Font(bold=True)
    for p in range(1, n_periods + 1):
        letter = get_column_letter(2 + p)
        formula = (
            f"={letter}{pv_total_row}" if p == 1
            else f"={get_column_letter(1 + p)}{curve_row}+{letter}{pv_total_row}"
        )
        c = ws.cell(row=curve_row, column=2 + p, value=formula)
        c.number_format, c.fill, c.font, c.border = RUPEES, FORMULA_FILL, Font(bold=True), BOX

    ws.cell(row=curve_row + 2, column=2,
            value="The final cumulative value must equal BAC exactly.").font = NOTE_FONT
    c = ws.cell(row=curve_row + 2, column=3 + n_periods,
                value=f'=IF(ROUND({get_column_letter(1 + n_periods)}{curve_row}'
                      f"-Inputs!C{inputs_rows[2]},2)=0,\"OK\",\"MISMATCH\")")
    c.fill, c.border = FORMULA_FILL, BOX
    ws.freeze_panes = "C5"

    curve_range = f"Baseline!$C${curve_row}:${get_column_letter(2 + n_periods)}${curve_row}"

    # ======================================================================
    # Calc P5 / Calc P6  (per-package earned value)
    # ======================================================================
    for period in BENCHMARK_PERIODS:
        ws = wb.create_sheet(f"Calc P{period}")
        _title(
            ws, f"Earned Value by Work Package — end of Period {period}"
                f" ({project.meta.label(period)})",
            "EV = cumulative percent complete x budget.  "
            "PV and AC are cumulative to this period.",
        )
        _header_row(
            ws, 4,
            ["WBS ID", "Work Package", "Budget (Rs)", "% Complete",
             "EV (Rs)", "PV cum (Rs)", "AC cum (Rs)", "CV (Rs)", "SV (Rs)", "CPI", "SPI"],
            [10, 44, 16, 12, 16, 16, 16, 15, 15, 11, 11],
        )

        pct_col = get_column_letter(3 + data_date + period)
        ac_last_col = get_column_letter(3 + period)
        pv_last_col = get_column_letter(2 + period)

        for i, row in leaves.iterrows():
            r = first + i
            src = first + i
            ws.cell(row=r, column=1, value=row["wbs_id"]).border = BOX
            ws.cell(row=r, column=2, value=row["name"]).border = BOX

            c = ws.cell(row=r, column=3, value=f"=Inputs!C{src}")
            c.number_format, c.border = RUPEES, BOX

            c = ws.cell(row=r, column=4, value=f"=Inputs!{pct_col}{src}")
            c.number_format, c.border = PCT, BOX

            # The definition of earned value, one cell.
            c = ws.cell(row=r, column=5, value=f"=C{r}*D{r}")
            c.number_format, c.fill, c.border = RUPEES, FORMULA_FILL, BOX

            c = ws.cell(row=r, column=6, value=f"=SUM(Baseline!C{src}:{pv_last_col}{src})")
            c.number_format, c.fill, c.border = RUPEES, FORMULA_FILL, BOX

            c = ws.cell(row=r, column=7, value=f"=SUM(Inputs!D{src}:{ac_last_col}{src})")
            c.number_format, c.fill, c.border = RUPEES, FORMULA_FILL, BOX

            c = ws.cell(row=r, column=8, value=f"=E{r}-G{r}")
            c.number_format, c.fill, c.border = RUPEES, FORMULA_FILL, BOX

            c = ws.cell(row=r, column=9, value=f"=E{r}-F{r}")
            c.number_format, c.fill, c.border = RUPEES, FORMULA_FILL, BOX

            c = ws.cell(row=r, column=10, value=f'=IF(G{r}=0,"",E{r}/G{r})')
            c.number_format, c.fill, c.border = INDEX_FMT, FORMULA_FILL, BOX

            c = ws.cell(row=r, column=11, value=f'=IF(F{r}=0,"",E{r}/F{r})')
            c.number_format, c.fill, c.border = INDEX_FMT, FORMULA_FILL, BOX

        trow = last + 1
        ws.cell(row=trow, column=2, value="PROJECT TOTAL").font = Font(bold=True)
        for col in range(3, 10):
            letter = get_column_letter(col)
            c = ws.cell(row=trow, column=col, value=f"=SUM({letter}{first}:{letter}{last})")
            c.number_format, c.fill, c.font, c.border = RUPEES, TOTAL_FILL, Font(bold=True), BOX
        c = ws.cell(row=trow, column=10, value=f"=E{trow}/G{trow}")
        c.number_format, c.fill, c.font, c.border = INDEX_FMT, TOTAL_FILL, Font(bold=True), BOX
        c = ws.cell(row=trow, column=11, value=f"=E{trow}/F{trow}")
        c.number_format, c.fill, c.font, c.border = INDEX_FMT, TOTAL_FILL, Font(bold=True), BOX
        ws.freeze_panes = "C5"

    calc_total_row = last + 1

    # ======================================================================
    # Indices  (everything, both periods, side by side)
    # ======================================================================
    ws = wb.create_sheet("Indices")
    _title(
        ws, "EVM Indices and Forecasts",
        "Every cell is a formula. Compare against the tool output in docs/04-validation-report.md.",
    )
    _header_row(ws, 4, ["#", "Measure", "Formula as applied",
                        f"Period {BENCHMARK_PERIODS[0]}", f"Period {BENCHMARK_PERIODS[1]}",
                        "Unit"],
                [5, 38, 44, 20, 20, 10])

    p5, p6 = BENCHMARK_PERIODS
    s5, s6 = f"'Calc P{p5}'!", f"'Calc P{p6}'!"
    t = calc_total_row

    def pair(expr: str) -> tuple[str, str]:
        """Same formula for both periods, with the sheet prefix substituted."""
        return f"={expr.format(s=s5, t=t)}", f"={expr.format(s=s6, t=t)}"

    bac_ref = f"Inputs!C{inputs_rows[2]}"
    ev = "{s}E{t}"
    pv_ = "{s}F{t}"
    ac_ = "{s}G{t}"

    rows: list[tuple[str, str, str, str, str]] = []

    def add(label, shown, expr, unit, fmt=RUPEES):
        rows.append((label, shown, expr, unit, fmt))

    add("Budget at completion (BAC)", "Sum of all work package budgets",
        bac_ref.replace("{", "{{").replace("}", "}}"), "Rs")
    add("Planned value (PV)", "Cumulative time-phased budget to date", pv_, "Rs")
    add("Earned value (EV)", "Sum of (% complete x budget)", ev, "Rs")
    add("Actual cost (AC)", "Cumulative cost booked to date", ac_, "Rs")
    add("Cost variance (CV)", "EV - AC", f"{ev}-{ac_}", "Rs")
    add("Schedule variance (SV)", "EV - PV", f"{ev}-{pv_}", "Rs")
    add("Cost variance %", "CV / EV", f"({ev}-{ac_})/{ev}", "%", PCT)
    add("Schedule variance %", "SV / PV", f"({ev}-{pv_})/{pv_}", "%", PCT)
    add("Cost performance index (CPI)", "EV / AC", f"{ev}/{ac_}", "ratio", INDEX_FMT)
    add("Schedule performance index (SPI)", "EV / PV", f"{ev}/{pv_}", "ratio", INDEX_FMT)
    add("Percent complete", "EV / BAC", f"{ev}/{bac_ref}", "%", PCT)
    add("Percent spent", "AC / BAC", f"{ac_}/{bac_ref}", "%", PCT)
    add("Percent scheduled", "PV / BAC", f"{pv_}/{bac_ref}", "%", PCT)

    # Earned Schedule. MATCH on an ascending cumulative PV curve returns the
    # last period whose cumulative planned value does not exceed EV; the
    # remainder is interpolated linearly across the following period.
    n_expr = f"MATCH({ev},{curve_range},1)"
    es_expr = (
        f"IFERROR({n_expr}+({ev}-INDEX({curve_range},{n_expr}))"
        f"/(INDEX({curve_range},{n_expr}+1)-INDEX({curve_range},{n_expr})),"
        f"{ev}/INDEX({curve_range},1))"
    )
    add("Earned schedule (ES)", "Baseline time at which PV equals current EV",
        es_expr, "periods", INDEX_FMT)
    add("Actual time (AT)", "Periods elapsed at the data date", "{period}", "periods", "0")
    add("Schedule variance, time SV(t)", "ES - AT", f"{es_expr}-{{period}}",
        "periods", INDEX_FMT)
    add("Schedule performance index SPI(t)", "ES / AT", f"({es_expr})/{{period}}",
        "ratio", INDEX_FMT)

    remaining = f"({bac_ref}-{ev})"
    add("EAC method 1", "BAC / CPI", f"{bac_ref}/({ev}/{ac_})", "Rs")
    add("EAC method 2", "AC + (BAC - EV)", f"{ac_}+{remaining}", "Rs")
    add("EAC method 3", "AC + (BAC - EV) / (CPI x SPI)",
        f"{ac_}+{remaining}/(({ev}/{ac_})*({ev}/{pv_}))", "Rs")
    add("EAC method 4", "AC + (BAC - EV) / (0.8 CPI + 0.2 SPI)",
        f"{ac_}+{remaining}/(0.8*({ev}/{ac_})+0.2*({ev}/{pv_}))", "Rs")
    add("ETC (on EAC method 1)", "EAC1 - AC", f"{bac_ref}/({ev}/{ac_})-{ac_}", "Rs")
    add("VAC (on EAC method 1)", "BAC - EAC1", f"{bac_ref}-{bac_ref}/({ev}/{ac_})", "Rs")
    add("TCPI to BAC", "(BAC - EV) / (BAC - AC)", f"{remaining}/({bac_ref}-{ac_})",
        "ratio", INDEX_FMT)
    add("TCPI to EAC1", "(BAC - EV) / (EAC1 - AC)",
        f"{remaining}/({bac_ref}/({ev}/{ac_})-{ac_})", "ratio", INDEX_FMT)

    for n, (label, shown, expr, unit, fmt) in enumerate(rows, start=1):
        r = 4 + n
        ws.cell(row=r, column=1, value=n).border = BOX
        ws.cell(row=r, column=2, value=label).border = BOX
        c = ws.cell(row=r, column=3, value=shown)
        c.font, c.border = Font(size=9, color="595959"), BOX
        for col, (sheet, period) in enumerate(
            ((s5, p5), (s6, p6)), start=4
        ):
            formula = "=" + expr.format(s=sheet, t=t, period=period)
            c = ws.cell(row=r, column=col, value=formula)
            c.number_format, c.fill, c.border = fmt, FORMULA_FILL, BOX
            c.font = Font(bold=True, size=11)
        c = ws.cell(row=r, column=6, value=unit)
        c.font, c.border = NOTE_FONT, BOX
        c.alignment = Alignment(horizontal="center")

    note_row = 5 + len(rows) + 1
    for i, line in enumerate([
        "Notes",
        "1. Rounding is applied by the cell number format only. No value is rounded in the "
        "calculation chain; rounding an intermediate index moves EAC method 3 by tens of rupees.",
        "2. Earned Schedule assumes planned value accrues linearly within a period. Over a "
        "monthly period on building work this is a mild assumption.",
        "3. TCPI to EAC1 must equal CPI exactly. It is an algebraic identity and a check that "
        "the forecast chain is intact.",
        "4. EAC method 2 implies VAC equal to the cost variance already incurred. Also an identity.",
    ]):
        c = ws.cell(row=note_row + i, column=2, value=line)
        c.font = Font(bold=True, size=10) if i == 0 else NOTE_FONT
    ws.freeze_panes = "D5"

    # Tell the spreadsheet application to recalculate everything on open.
    # openpyxl writes formulas but no cached results, so without this flag a
    # reader that trusts the cache sees empty cells. It is also what lets
    # the validation script drive LibreOffice headlessly to evaluate the
    # workbook rather than re-implementing the formulas in Python, which
    # would only confirm our own understanding of them.
    wb.calculation.fullCalcOnLoad = True

    OUT.parent.mkdir(parents=True, exist_ok=True)
    wb.save(OUT)
    return OUT


if __name__ == "__main__":
    path = build()
    print(f"Written: {path}")
    print("Formulas placed, not evaluated. Run scripts/recalculate.py to compute them.")
